fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    passthrough_dep_z3_version();

    #[cfg(feature = "bindgen")]
    generate_and_write_bindings();
}

/// Reads the Z3 version z3-sys detected, via the `links = "z3"` metadata
/// passthrough (`DEP_Z3_VERSION_MAJOR`/`MINOR`/`PATCH` in `z3/build.rs`),
/// emitted by z3-sys/build.rs.
fn passthrough_dep_z3_version() {
    dbg!(std::env::vars());
    // unreachable!();
    for s in ["MAJOR", "MINOR", "PATCH"] {
        let key = format!("VERSION_{}", s);
        let depkey = format!("DEP_Z3_{}", key);
        println!("cargo::rerun-if-env-changed={}", depkey);
        let Some(component) = std::env::var(&depkey)
            .ok()
            .and_then(|s| s.parse::<u32>().ok())
        else {
            continue;
        };
        println!("cargo:{}={}", key, component);
    }
}

#[cfg(feature = "bindgen")]
fn generate_and_write_bindings() {
    use std::env;
    use std::fs;
    use std::path::PathBuf;

    let output = z3_sys::bindgen::generate_bindings();

    let header_comment = "// Auto-generated by z3-sys bindgen feature — do not edit manually.\n\n";
    let funcs_wrappers_src = format!("{header_comment}{}", output.functions_wrappers);

    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out.join("functions.rs"), &funcs_wrappers_src)
        .expect("write functions.rs to OUT_DIR");

    if env::var("Z3_SYS_UPDATE_GENERATED").is_ok() {
        let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
        let r#gen = manifest.join("src/generated");

        let committed_funcs = r#gen.join("functions.rs");
        fs::write(&committed_funcs, &funcs_wrappers_src).expect("write committed functions.rs");
        println!("cargo:warning=Updated {}", committed_funcs.display());
    }
}
